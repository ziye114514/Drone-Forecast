def camera_circle(tilt,azimuth,diameter,off_axis=False):
    """Camera axes: x right, y down, z forwards; plane is prescribed in 3D."""
    a,b=np.deg2rad([tilt,azimuth]);normal=np.array([np.sin(a)*np.sin(b),-np.sin(a)*np.cos(b),np.cos(a)])
    u=unit(np.array([1.,0,0])-normal*normal[0]);v=np.cross(normal,u)
    K=np.array([[800.,0,640],[0,800,360],[0,0,1.]])
    radius=.1;z=160./diameter
    center=np.array([.42*z,.18*z,z]) if off_axis else np.array([0.,0.,z])
    H=K@np.column_stack((radius*u,radius*v,center))
    C=np.linalg.inv(H).T@np.diag([1.,1.,-1.])@np.linalg.inv(H)
    A=C[:2,:2];c=-np.linalg.solve(A,C[:2,2]);scale=-(c@A@c+2*C[:2,2]@c+C[2,2])
    values,vectors=np.linalg.eigh(A/scale);axes=1/np.sqrt(values);angle=np.arctan2(vectors[1,0],vectors[0,0])%np.pi
    return dict(K=K,H=H,normal=normal,ellipse=np.r_[c,axes,angle],physical_center=K@center/center[2])

def project(H,points):
    q=np.column_stack((points,np.ones(len(points))))@H.T
    return q[:,:2]/q[:,2,None]

def normal_error(a,b):return float(np.rad2deg(np.arccos(np.clip(abs(unit(a)@unit(b)),0,1))))

def ellipse_from_cv(points):
    try:
        (x,y),(d1,d2),angle=cv2.fitEllipseAMS(np.float32(points).reshape(-1,1,2))
        if d1<d2:d1,d2,angle=d2,d1,angle+90
        if min(d1,d2)<=0 or not np.isfinite([x,y,d1,d2,angle]).all():return None
        return dict(center=np.array([x,y]),major=d1,minor=d2,angle=angle%180,ratio=d2/d1,
            axis_only=False,mode='unbounded_AMS',geometry_quality=None)
    except cv2.error:return None

def geometry():
    cfg=verify()['geometry'];rows=[];checks=[];start=time.perf_counter()
    grid=itertools.product(cfg['tilt_deg'],cfg['off_axis'],cfg['diameter_px'],cfg['visible_arc_deg'],cfg['noise_sigma_px'],cfg['seeds'],cfg['azimuth_deg'])
    for index,(tilt,off,diameter,arc,noise,seed,azi) in enumerate(grid):
        world=camera_circle(tilt,azi,diameter,off);gt=world['ellipse'];rng=np.random.default_rng(seed)
        phase=np.linspace(.3,.3+np.deg2rad(arc),cfg['points'],endpoint=False)
        points=project(world['H'],np.column_stack((np.cos(phase),np.sin(phase))))+rng.normal(0,noise,(cfg['points'],2))
        # Past prior is a separate noisy full observation, not an exact truth prior.
        past_phase=np.linspace(0,2*np.pi,cfg['points'],endpoint=False)
        past=project(world['H'],np.column_stack((np.cos(past_phase),np.sin(past_phase))))+rng.normal(0,noise,(cfg['points'],2))
        prior=fit_rotor_geometry(past,640,None,True)
        estimates=[ellipse_from_cv(points),fit_rotor_geometry(points,640,None,True),fit_rotor_geometry(points,640,prior,True)]
        exact=circle_normal_candidates(gt,world['K'])
        exact_error=min(normal_error(n,world['normal']) for n in exact)
        checks.append(exact_error)
        for name,m in zip(cfg['methods'],estimates):
            r=dict(case=index,tilt_deg=tilt,off_axis=off,diameter_px=diameter,arc_deg=arc,noise_px=noise,seed=seed,azimuth_deg=azi,
                method=name,accepted=m is not None,exact_conic_candidate_error_deg=exact_error)
            if m:
                r.update(mode=m['mode'],axis_only=m['axis_only'],quality=m['geometry_quality'],
                    center_error_px=float(np.linalg.norm(m['center']-gt[:2])),diameter_relative_error=abs(m['major']-2*gt[2])/(2*gt[2]),
                    ratio_error=abs(m['ratio']-gt[3]/gt[2]),true_ratio=gt[3]/gt[2])
                if tilt>0:r['image_axis_error_deg']=float(abs((np.rad2deg(gt[4])-m['angle']+90)%180-90))
                if not m['axis_only']:
                    ellipse=np.r_[m['center'],m['major']/2,m['minor']/2,np.deg2rad(m['angle'])]
                    try:
                        candidates=circle_normal_candidates(ellipse,world['K'])
                        r['best_calibrated_candidate_error_deg']=min(normal_error(n,world['normal']) for n in candidates)
                        chosen=max([s*n for n in candidates for s in (-1,1)],key=lambda n:n@[0.,-1.,0.])
                        r['initialized_up_prior_error_deg']=normal_error(chosen,world['normal'])
                    except (ValueError,np.linalg.LinAlgError):r['calibrated_failed']=True
                    weak=weak_normal(m)
                    # Report both the deployed initial up choice and ambiguity-aware bound.
                    r['weak_up_prior_error_deg']=normal_error(weak,world['normal'])
                    r['weak_ambiguity_bound_deg']=min(normal_error(weak,world['normal']),normal_error(np.r_[-weak[:2],weak[2]],world['normal']))
            rows.append(r)
        if index%300==0:print(json.dumps(dict(phase='geometry',case=index,wall_s=round(time.perf_counter()-start,1))),flush=True)
    assert max(checks)<.001,'Analytic conic inverse must recover a valid truth candidate'
    csvsave(OUT/'geometry_cases.csv',rows)
    save(OUT/'geometry_completion.json',dict(cases=index+1,rows=len(rows),max_exact_candidate_error_deg=max(checks),wall_s=time.perf_counter()-start))

def render_events(world,rps,half,seed,duration=.16,dt_us=25):
    """Pixel intensity sampling independent of the inverse ellipse fit/FFT."""
    rng=np.random.default_rng(seed);e=world['ellipse'];cx,cy,a,b,angle=e
    # Homography maps physical normalized plane to the actual image pixels.
    lo=np.floor([cx-a-3,cy-a-3]).astype(int);hi=np.ceil([cx+a+3,cy+a+3]).astype(int)
    yy,xx=np.mgrid[lo[1]:hi[1]+1,lo[0]:hi[0]+1];xy=np.column_stack((xx.ravel(),yy.ravel(),np.ones(xx.size)))
    q=xy@np.linalg.inv(world['H']).T;plane=q[:,:2]/q[:,2,None];radius=np.linalg.norm(plane,axis=1)
    support=(radius>.18)&(radius<1.)
    if half:support&=xx.ravel()>=cx
    plane=plane[support];xx=xx.ravel()[support];yy=yy.ravel()[support]
    theta=np.arctan2(plane[:,1],plane[:,0]);radial=np.linalg.norm(plane,axis=1)
    # Rectangular two-blade cross-section, radial length .18..1, halfwidth .07R.
    half_angle=np.arcsin(np.minimum(.99,.07/radial));phase0=rng.uniform(0,2*np.pi)
    log_low,log_high=np.log(.12),np.log(.72);threshold=.4
    def intensity(t):
        phase=theta-2*np.pi*rps*t-phase0
        distance=abs((phase+np.pi/2)%np.pi-np.pi/2)
        return np.where(distance<half_angle,log_high,log_low)
    reference=intensity(0.);parts=[];image=np.zeros((720,1280),np.int32)
    for stamp in range(dt_us,round(duration*1e6),dt_us):
        value=intensity(stamp/1e6);delta=value-reference
        count=np.floor(np.abs(delta)/threshold+1e-8).astype(int);selected=count>0
        if not selected.any():continue
        indexes=np.repeat(np.flatnonzero(selected),count[selected]);piece=np.zeros(len(indexes),DTYPE)
        piece['x']=xx[indexes];piece['y']=yy[indexes];piece['p']=delta[indexes]>0;piece['t']=stamp
        parts.append(piece);reference[selected]+=np.sign(delta[selected])*count[selected]*threshold
    noise=np.zeros(rng.poisson(duration*2000),DTYPE);noise['x']=rng.integers(0,1280,len(noise));noise['y']=rng.integers(0,720,len(noise))
    noise['t']=rng.integers(0,round(duration*1e6),len(noise));noise['p']=rng.integers(0,2,len(noise));parts.append(noise)
    events=np.concatenate(parts);events.sort(order='t');np.add.at(image,(events['y'],events['x']),1)
    return events,image

def raster():
    p=verify()['raster'];rows=[];folder=OUT/'raster_samples';folder.mkdir(exist_ok=True);started=time.perf_counter()
    for index,(rps,tilt,diameter,half,seed) in enumerate(itertools.product(p['rps'],p['tilt_deg'],p['diameter_px'],p['half_occlusion'],p['seeds'])):
        world=camera_circle(tilt,20,diameter);e,image=render_events(world,rps,half,seed)
        x,y,a,b,angle=world['ellipse'];rotor=dict(cx=x,cy=y,major=2*a,minor=2*b,angle=np.rad2deg(angle),ratio=b/a,axis_only=b/a<.08)
        measured=periodic_measurement(e,rotor,[0,0],.16,PaperConfig())
        row=dict(case=index,rps=rps,mechanical_rpm=rps*60,blade_pass_truth_hz=rps*2,tilt_deg=tilt,diameter_px=diameter,
                 half_occlusion=half,seed=seed,events=len(e),true_ratio=b/a,**measured)
        if measured['valid']:
            row['relative_frequency_error']=abs(measured['blade_pass_hz']/(rps*2)-1)
            row['correct_within_5pct']=row['relative_frequency_error']<=.05
            row['double_or_half_error']=min(abs(measured['blade_pass_hz']/(rps*2)-.5),abs(measured['blade_pass_hz']/(rps*2)-2))<.1
        rows.append(row)
        if seed==70 and rps==120:
            canvas=np.uint8(np.clip(np.log1p(image)/7,0,1)*255)
            cv2.imwrite(str(folder/f'tilt_{tilt}_d{diameter}_half{int(half)}.png'),canvas)
            if tilt in (20,88) and diameter==96 and not half:np.savez_compressed(folder/f'events_tilt_{tilt}.npz',events=e)
        if index%8==0:print(json.dumps(dict(phase='raster',case=index,wall_s=round(time.perf_counter()-started,1))),flush=True)
    csvsave(OUT/'raster_frequency_cases.csv',rows);save(OUT/'raster_completion.json',dict(cases=len(rows),wall_s=time.perf_counter()-started))

