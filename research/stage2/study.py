def fred():
    p=verify()['fred'];raw=FIRST/'public_truth_substitutes/fred_sequence1/events.raw'
    reader=open_raw(raw);height,width=reader.get_size();front=PaperPerception(width,height,PaperConfig());records=[];counts={}
    candidates=[];original=front._candidates
    def observe(contours,activity,t,b,thin_only=False):
        found=original(contours,activity,t,b,thin_only)
        key='thin' if thin_only else 'normal';counts[key+'_contours']=len(contours);counts[key+'_candidates']=len(found)
        candidates.extend([dict(cx=float(r['center'][0]),cy=float(r['center'][1]),major=r['major'],minor=r['minor'],mode=r['mode']) for r in found])
        return found
    front._candidates=observe;started=time.perf_counter();lastprint=started
    for t,e in raw_chunks(reader,0,p['duration_s'],10000):
        candidates=[];counts={};o,image=front.detect(e,t)
        pixel=e['y'].astype(int)*width+e['x'];total=np.bincount(pixel,minlength=width*height)
        pos=np.bincount(pixel[e['p']>0],minlength=width*height);both=np.minimum(pos,total-pos)
        record=dict(t=t,n_events=len(e),bipolar_pixels=int((both>0).sum()),**counts,detected=o['detected'],
            center=o.get('center'),selected_rotors=len(o['rotors']),candidates=candidates)
        records.append(record)
        if time.perf_counter()-lastprint>12:
            print(json.dumps(dict(phase='fred_audit',t=t)),flush=True);lastprint=time.perf_counter()
    folder=OUT/'fred_diagnosis';folder.mkdir(exist_ok=True)
    with (folder/'frontend_traces.jsonl').open('w',encoding='utf-8') as f:
        for r in records:f.write(json.dumps(r)+'\n')
    original_obs=[json.loads(line) for line in (raw.parent/'raw_only_baseline/observations.jsonl').read_text().splitlines()]
    assert len(original_obs)==len(records)==2000
    for a,b in zip(original_obs,records):
        assert a['detected']==b['detected']
        if a['detected']:np.testing.assert_array_equal(a['center'],b['center'])
    # Labels are opened AFTER inference and instrumentation equivalence checks.
    labels=[]
    for line in (raw.parent/'coordinates.txt').read_text().splitlines():
        stamp,values=line.split(':',1);box=np.array(list(map(float,values.split(',')[:4])))
        labels.append(dict(t=float(stamp),bbox=box))
    times=np.array([r['t'] for r in records]);rows=[]
    for label in labels:
        if not 0<label['t']<=20:continue
        k=np.searchsorted(times,label['t'],side='right')-1
        if k<0:continue
        r=records[k];box=label['bbox'];center=(box[:2]+box[2:])/2
        hits=[q for q in r['candidates'] if box[0]<=q['cx']<=box[2] and box[1]<=q['cy']<=box[3]]
        row={key:r[key] for key in ('t','n_events','bipolar_pixels','normal_contours','thin_contours','normal_candidates','thin_candidates','detected','selected_rotors')}
        row.update(label_time_s=label['t'],box_width_px=box[2]-box[0],box_height_px=box[3]-box[1],candidate_centers_in_box=len(hits))
        if r['detected']:row['center_error_px']=float(np.linalg.norm(r['center']-center))
        rows.append(row)
    csvsave(folder/'posthoc_annotation_diagnosis.csv',rows)
    save(folder/'completion.json',dict(frames=len(records),label_times=len(rows),inference_unchanged_verified=True,
        zero_candidates_at_labels=sum(r['normal_candidates']+r['thin_candidates']==0 for r in rows),
        no_candidates_in_target_box=sum(r['candidate_centers_in_box']==0 for r in rows),
        exactly_one_candidate_in_target_box=sum(r['candidate_centers_in_box']==1 for r in rows),
        at_least_two_candidates_in_target_box=sum(r['candidate_centers_in_box']>=2 for r in rows),
        detected_at_labels=sum(r['detected'] for r in rows),wall_s=time.perf_counter()-started,labels_used_in_inference=False))
    print('FRED diagnosis done',flush=True)

